from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # draw to files only, no window
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

# Colours from a colour-blind-checked categorical palette; text stays in neutral ink.
KEPT, DROPPED, INK, MUTED = "#2a78d6", "#eb6834", "#0b0b0b", "#52514e"
PNG_META = {"Software": None}  # no version string in the PNG, so files stay byte-identical


def df_to_md(df: pd.DataFrame) -> str:
    """Minimal markdown table (avoids an extra dependency)."""
    head = [str(df.index.name or "")] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for i, r in df.iterrows():
        lines.append("| " + " | ".join([str(i)] + [str(v) for v in r.tolist()]) + " |")
    return "\n".join(lines)


def _style_axes(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(MUTED)
    ax.tick_params(colors=MUTED, labelsize=9)


def inspection_report(cfg: dict, raw: pd.DataFrame, out: Path) -> dict:
    """Facts about the downloaded data, before any filtering."""
    info = {
        "rows": int(len(raw)),
        "columns_in_parquet": ["audio (struct: bytes, path)", "text", "speaker_id", "style", "id"],
        "speaker_id_values": sorted(raw["speaker_id"].unique().tolist()),
        "style_values_with_counts": raw["style"].value_counts().sort_index().to_dict(),
        "decoded_sample_rates": {int(k): int(v) for k, v in raw["orig_sr"].value_counts().items()},
        "decoded_channels": {int(k): int(v) for k, v in raw["channels"].value_counts().items()},
        "duplicate_ids": int(raw["id"].duplicated().sum()),
        "rows_sharing_a_duplicated_id": int(raw["id"].duplicated(keep=False).sum()),
        "identical_audio_extra_copies": int(raw["audio_sha256"].duplicated().sum()),
        "empty_text": int((raw["text"].fillna("").str.strip() == "").sum()),
        "duration_s_by_style": raw.groupby("style")["duration_s"]
        .describe(percentiles=[0.5, 0.95])
        .round(2)
        .to_dict(orient="index"),
    }
    (out / "dataset_inspection.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
    pd.crosstab(raw["speaker_id"], raw["style"], margins=True).to_csv(out / "raw_counts_speaker_style.csv")
    return info


def counts_tables(manifest: pd.DataFrame, out: Path) -> pd.DataFrame:
    clips = pd.crosstab(manifest["actor"], manifest["style"], margins=True, margins_name="total")
    minutes = (
        manifest.pivot_table(index="actor", columns="style", values="duration_s", aggfunc="sum", margins=True,
                             margins_name="total")
        / 60
    ).round(1)
    clips.to_csv(out / "counts_actor_style_clips.csv")
    minutes.to_csv(out / "counts_actor_style_minutes.csv")
    combined = clips.astype(str) + " / " + minutes.reindex_like(clips).map(lambda v: f"{v:.1f}")
    md = ["Clips / minutes of real audio inside the model window, per actor x style (after all filtering; "
          "cropped clips count only their first max_seconds)", "", df_to_md(combined)]
    (out / "counts_actor_style.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return combined


def excluded_summary(excluded: pd.DataFrame, out: Path) -> pd.DataFrame:
    t = (
        excluded.groupby(["exclude_reason", "speaker_id", "style"]).size().rename("clips").reset_index()
        .sort_values(["exclude_reason", "speaker_id", "style"])
    )
    t.to_csv(out / "excluded_summary.csv", index=False)
    return t


def audio_warnings(cfg: dict, manifest: pd.DataFrame, out: Path) -> pd.DataFrame:
    a = cfg["audio"]
    w = manifest.assign(
        possibly_clipped=manifest["peak"] >= a["clip_warn_peak"],
        near_silent=manifest["rms_dbfs"] < a["silence_warn_dbfs"],
        over_full_scale_after_resample=manifest["n_over_full_scale_16k"] > 0,
    )
    flagged = w[w["possibly_clipped"] | w["near_silent"] | w["over_full_scale_after_resample"]]
    cols = ["clip_id", "actor", "style", "peak", "rms_dbfs", "n_over_full_scale_16k", "possibly_clipped",
            "near_silent", "over_full_scale_after_resample"]
    flagged[cols].to_csv(out / "audio_warnings.csv", index=False)
    return flagged[cols]


def duration_histogram(cfg: dict, durations: pd.Series, out: Path) -> None:
    """durations: ORIGINAL length of every 7-style clip after de-duplication (before any crop or drop)."""
    max_s = cfg["audio"]["max_seconds"]
    policy = cfg["audio"]["long_clip_policy"]
    fig, ax = plt.subplots(figsize=(8, 4))
    bins = np.arange(0, np.ceil(durations.max()) + 0.25, 0.25)
    fits, long = durations[durations <= max_s], durations[durations > max_s]
    verb = "cropped to the first" if policy == "crop" else "dropped, longer than"
    share = len(long) / len(durations)
    ax.hist([fits, long], bins=bins, stacked=True, color=[KEPT, DROPPED], edgecolor="white", linewidth=0.5,
            label=[f"fits in {max_s} s window ({len(fits)}, {1 - share:.1%})",
                   f"{verb} {max_s} s ({len(long)}, {share:.1%})"])
    ax.axvline(max_s, color=INK, linewidth=1, linestyle="--")
    ax.text(max_s, ax.get_ylim()[1] * 0.95, f"  {max_s} s window", color=INK, fontsize=9, va="top")
    ax.set_xlabel("original clip duration (seconds)", color=INK)
    ax.set_ylabel("number of clips", color=INK)
    ax.set_title("Durations of the 7-style clips (after removing duplicates)", color=INK, fontsize=11, loc="left")
    ax.legend(frameon=False, fontsize=9)
    _style_axes(ax)
    fig.tight_layout()
    fig.savefig(out / "duration_histogram.png", dpi=150, metadata=PNG_META)
    plt.close(fig)


def spectrogram_per_style(cfg: dict, manifest: pd.DataFrame, index: pd.DataFrame, out: Path) -> dict:
    """One log-mel image per style, same actor, the same sentence if one exists in all styles."""
    from src.data.spectrograms import load_logmel

    styles = cfg["labels"]["styles"]
    actor = cfg["reports"].get("example_actor") or sorted(manifest["actor"].unique())[0]
    m = manifest[manifest["actor"] == actor]
    n_styles_per_text = m.groupby("text_norm")["style"].nunique().sort_index()
    best = n_styles_per_text[n_styles_per_text == n_styles_per_text.max()].index[0]
    picks = {}
    for s in styles:
        cand = m[(m["style"] == s) & (m["text_norm"] == best)]
        if cand.empty:  # fall back to the first clip of that style
            cand = m[m["style"] == s]
        picks[s] = cand.sort_values("clip_id").iloc[0]
    idx = index.set_index("clip_id")
    sp = cfg["spectrogram"]
    max_valid = max(int(idx.loc[r.clip_id, "n_frames_valid"]) for r in picks.values())
    fig, axes = plt.subplots(len(styles), 1, figsize=(9, 2.0 * len(styles)), sharex=True, layout="constrained")
    vmax = 20.0
    vmin = -80.0
    for ax, s in zip(axes, styles):
        r = picks[s]
        x = np.asarray(load_logmel(cfg, idx.loc[r.clip_id]), dtype=np.float32)[:, :max_valid]
        t_end = max_valid * sp["hop_length"] / sp["sr"]
        im = ax.imshow(x, origin="lower", aspect="auto", cmap="magma", vmin=vmin, vmax=vmax,
                       extent=[0, t_end, 0, sp["n_mels"]])
        ax.axvline(r.duration_s, color="white", linewidth=0.8, linestyle=":")
        ax.set_ylabel("mel band", fontsize=8, color=MUTED)
        ax.set_title(f"{s}  ({r.clip_id}, {r.duration_s:.2f} s): {r.text[:70]}", fontsize=9, loc="left", color=INK)
        ax.tick_params(labelsize=8, colors=MUTED)
    axes[-1].set_xlabel("time (seconds); dotted line = end of real audio, right of it is padding", color=INK)
    cbar = fig.colorbar(im, ax=axes, shrink=0.6)
    cbar.set_label("dB (fixed reference, same scale for all panels)", fontsize=8)
    fig.suptitle(f"Log-mel spectrograms, actor {actor}, one clip per style", x=0.01, ha="left", fontsize=11)
    fig.savefig(out / "spectrograms_per_style.png", dpi=130, metadata=PNG_META)
    plt.close(fig)
    return {"actor": actor, "sentence": best, "styles_with_this_sentence": int(n_styles_per_text.max()),
            "clips": {s: r.clip_id for s, r in picks.items()}}


def cropped_table(manifest: pd.DataFrame, out: Path) -> pd.DataFrame:
    """Clips cropped to the window, per actor x style (count and share of that cell)."""
    n = pd.crosstab(manifest["actor"], manifest["style"], values=manifest["was_cropped"], aggfunc="sum",
                    margins=True, margins_name="total").astype(int)
    tot = pd.crosstab(manifest["actor"], manifest["style"], margins=True, margins_name="total")
    n.to_csv(out / "cropped_actor_style.csv")
    pct = (100 * n / tot).round(1)
    combined = n.astype(str) + " (" + pct.map(lambda v: f"{v:.1f}") + "%)"
    md = ["Clips cropped to the first max_seconds, per actor x style: count (share of that cell)", "",
          df_to_md(combined)]
    (out / "cropped_actor_style.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return combined


def split_summary(splits: dict, out: Path) -> pd.DataFrame:
    """Clips per split part x style (and per actor) for every split file."""
    rows = []
    for name, f in splits.items():
        t = pd.crosstab(f["split"], f["style"], margins=True, margins_name="total")
        a = pd.crosstab(f["split"], f["actor"], margins=True, margins_name="total").drop(columns="total")
        a = a.add_prefix("actor_")
        t = t.join(a)
        t.insert(0, "split_file", name)
        t.insert(1, "test_actor", ",".join(sorted(f.loc[f["split"] == "test", "actor"].unique())))
        t.insert(2, "share", (t["total"] / len(f)).round(4))
        rows.append(t.reset_index())
    s = pd.concat(rows, ignore_index=True).fillna(0)
    s.to_csv(out / "split_summary.csv", index=False)
    return s
